        st.subheader("نتيجة تقييمك:")
        if score <= 2:
            st.success(
                "الحالة العامة: منخفضة (لا تحتاج لشيء، أنت في حالة استقرار جيد)."
            )
        elif score <= 6:
            st.warning(
                "الحالة العامة: متوسطة (تحتاج إلى تهدئة وطمأنة نفسية وبعض التمارين)."
            )
